// API 엔드포인트
app.post('/api/analyze', async (req, res) => {
  try {
    const { memoText, apiKey } = req.body;

    if (!memoText || memoText.trim().length < 50) {
      return res.status(400).json({
        error: '회의 기록은 최소 50자 이상이어야 합니다.',
      });
    }

    if (!apiKey) {
      return res.status(400).json({
        error: 'Claude API 키가 필요합니다.',
      });
    }

    // Anthropic 클라이언트 초기화
    const client = new Anthropic({
      apiKey: apiKey,
    });

    // Claude API 호출
    const message = await client.messages.create({
      model: 'claude-3-5-sonnet-20241022',
      max_tokens: 2000,
      messages: [
        {
          role: 'user',
          content: `${SECRETARY_PROMPT}\n\n[사용자의 회의 기록]\n${memoText}`,
        },
      ],
    });

    const result = message.content[0].type === 'text' ? message.content[0].text : '';

    res.json({
      success: true,
      result: result,
      timestamp: new Date().toISOString(),
    });
  } catch (error) {
    console.error('API Error:', error);

    if (error.status === 401) {
      res.status(401).json({
        error: 'API 키가 유효하지 않습니다. 다시 확인해주세요.',
      });
    } else if (error.status === 429) {
      res.status(429).json({
        error: 'API 요청 한도에 도달했습니다. 잠시 후 다시 시도해주세요.',
      });
    } else {
      res.status(500).json({
        error: `오류가 발생했습니다: ${error.message}`,
      });
    }
  }
});

